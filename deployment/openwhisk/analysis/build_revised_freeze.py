"""Build the REVISED authoritative OpenWhisk-vs-workstation effectiveness freeze.

One-time, pre-registered freeze revision (revision_id ``ow-eff-revision-2026-08-30``)
that supersedes exactly SEVEN of the 55 first-query cells with their targeted,
independently rebuilt, exactly position-balanced replication estimates:

  * five cells from the SIXTH campaign  ``portability_outlier_replication``
  * two   cells from the SEVENTH campaign ``portability_ych01_followup``

The other 48 cells are byte-carried from the historical freeze. Precedence
(applied per cell, only where a later campaign actually targeted that cell):
seventh > sixth > historical. No other cell may move.

Guarantees (see the controlling revision spec):
  * The historical freeze is preserved byte-identically (git history + an explicit
    ``*_historical_freeze.csv`` snapshot). Nothing is deleted.
  * The revised freeze is the SINGLE paper-facing input for figures/tables/stats.
  * Fail-closed: every superseded cell's audited value + provenance is loaded
    mechanically from the campaign audit outputs; if any expected cell/value/
    provenance cannot be resolved, this aborts WITHOUT writing.
  * Rounded values from the human-facing spec are NEVER written; only the exact
    machine values already generated by the repository are used.

This script only READS already-frozen campaign audit outputs. It does not run,
alter, or reinterpret any OpenWhisk evidence. Position effects are described only
as pair-position / short-lived execution-state / execution-storage-state effects
-- never attributed to page-cache carryover.
"""
