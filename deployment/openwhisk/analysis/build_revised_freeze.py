def _read_diag(path, r_col):
    """Return {(workload,strategy): row-dict} from a campaign position-diagnostics CSV,
    normalising the effectiveness column name (all_balanced_R / all_R) to 'R'."""
    out = {}
    with open(path) as f:
        for r in csv.DictReader(f):
            r = dict(r)
            r["R"] = float(r[r_col])
            out[(r["workload"], r["strategy"])] = r
    return out


def _seed_count_and_pairs(path, ws, strat):
    """Count distinct standalone seeds and total standalone pairs for one cell in a
    campaign's normalized_pairs.csv (ground-truth cross-check for fail-closed)."""
    seeds, npairs = set(), 0
    with open(path) as f:
        for row in csv.DictReader(f):
            if row["handle_mode"] != "standalone":
                continue
            if row["workload"] != ws or row["paired_target_strategy"] != strat:
                continue
            seeds.add(row["seed"])
            npairs += 1
    return len(seeds), npairs


# OpenWhisk workload_id -> workstation code (the diagnostics already use ws codes,
# but the pair files use OW ids). Reverse map for the seed cross-check.
WS_TO_OWID = {
    "YC": "native_ycsb_c_read_zipf",
    "YCu": "native_ycsb_c_read_uniform",
    "YCh01": "native_ycsb_c_hot_hashed_01",
    "C": "read_tail_mixed_20k",
    "C_hit": "read_tail_hit_20k",
}


def load_superseding_values():
    """Mechanically resolve every superseded cell's audited value + provenance.
    Fails closed (SystemExit) if any expected cell/value/provenance is missing or
    internally inconsistent."""
    sixth = _read_diag(SIXTH_DIAG, "all_balanced_R")
    seventh = _read_diag(SEVENTH_DIAG, "all_R")

    resolved = {}
    for (ws, strat), campaign in SUPERSEDE.items():
        diag = sixth if campaign == SIXTH else seventh
        pairs_path = SIXTH_PAIRS if campaign == SIXTH else SEVENTH_PAIRS
        if (ws, strat) not in diag:
            raise SystemExit(f"FAIL-CLOSED: {ws}/{strat} absent from {campaign} diagnostics")
        d = diag[(ws, strat)]
        n_bf = int(d["n_baseline_first"])
        n_tf = int(d["n_target_first"])
        same_sign = d["position_subsets_same_sign"].strip().lower() == "true"
        n_pairs = n_bf + n_tf

        # ground-truth cross-check against the campaign's normalized pairs
        owid = WS_TO_OWID[ws]
        n_seeds, n_pairs_pf = _seed_count_and_pairs(pairs_path, owid, strat)
        if n_pairs_pf != n_pairs:
            raise SystemExit(
                f"FAIL-CLOSED: {ws}/{strat} pair count mismatch: diagnostics {n_pairs} "
                f"vs normalized_pairs {n_pairs_pf}")
        if n_bf != n_tf:
            raise SystemExit(
                f"FAIL-CLOSED: {ws}/{strat} is not exactly position-balanced "
                f"({n_bf} baseline-first vs {n_tf} target-first)")

        bf = float(d["baseline_first_R"])
        tf = float(d["target_first_R"])
        resolved[(ws, strat)] = {
            "R_ow": d["R"],
            "baseline_first_R_ow": bf,
            "target_first_R_ow": tf,
            "n_ow_pairs": n_pairs,
            "n_ow_seeds": n_seeds,
            "ow_pos": f"{n_tf}/{n_bf}",              # tgt_first/base_first
            "position_sensitive": (not same_sign),
            "position_effect_direction":
                "target_first_higher" if tf > bf else "baseline_first_higher",
            "evidence_campaign": campaign,
            "execution_git_sha": SIXTH_GIT_SHA if campaign == SIXTH else SEVENTH_GIT_SHA,
            "run_config_sha256": SIXTH_RUN_CONFIG if campaign == SIXTH else SEVENTH_RUN_CONFIG,
        }
    # every one of the seven must be resolved
    missing = set(SUPERSEDE) - set(resolved)
    if missing:
        raise SystemExit(f"FAIL-CLOSED: unresolved superseded cells: {sorted(missing)}")
    return resolved


META_FIELDS = ["position_sensitive", "position_effect_direction",
               "baseline_first_R_ow", "target_first_R_ow",
               "evidence_pair_count", "exact_position_balance", "evidence_campaign"]


def build():
    if not HISTORICAL.exists():
        raise SystemExit(f"FAIL-CLOSED: historical freeze missing: {HISTORICAL}")
    hist_bytes = HISTORICAL.read_bytes()
    hist_sha = hashlib.sha256(hist_bytes).hexdigest()
    if hist_sha != HISTORICAL_SHA256_EXPECTED:
        raise SystemExit(
            f"FAIL-CLOSED: historical freeze SHA256 changed.\n  expected "
            f"{HISTORICAL_SHA256_EXPECTED}\n  found    {hist_sha}\n"
            "Refusing to revise a mutated historical source.")

    hist_rows = list(csv.DictReader(hist_bytes.decode().splitlines()))
    if len(hist_rows) != 55:
        raise SystemExit(f"FAIL-CLOSED: expected 55 historical cells, got {len(hist_rows)}")

    sup = load_superseding_values()

    superseded_manifest = []
    out_rows = []
    for r in hist_rows:
        key = (r["workload"], r["strategy"])
        row = dict(r)
        # default metadata (unchanged historical cells)
        row.update({
            "position_sensitive": "False",
            "position_effect_direction": "",
            "baseline_first_R_ow": "",
            "target_first_R_ow": "",
            "evidence_pair_count": "",
            "exact_position_balance": "",
            "evidence_campaign": "historical",
        })
        if key in sup:
            s = sup[key]
            R_ws = float(r["R_ws"])
            old_R_ow = float(r["R_ow"])
            R_ow = s["R_ow"]
            imbalance = 0  # exactly balanced by construction (asserted in loader)
            low_conf = (s["n_ow_pairs"] <= 3) or (imbalance == s["n_ow_pairs"])
            row.update({
                "R_ow": f"{R_ow:.4f}",
                "n_ow_pairs": str(s["n_ow_pairs"]),
                "n_ow_seeds": str(s["n_ow_seeds"]),
                "ow_pos": s["ow_pos"],
                "cat_ow": category(R_ow),
                "sign_agree": str(category(R_ws) == category(R_ow)),
                "abs_diff": f"{abs(R_ow - R_ws):.4f}",
                "low_conf": str(low_conf),
                "position_sensitive": str(s["position_sensitive"]),
                "position_effect_direction": s["position_effect_direction"],
                "baseline_first_R_ow": f"{s['baseline_first_R_ow']:.4f}",
                "target_first_R_ow": f"{s['target_first_R_ow']:.4f}",
                "evidence_pair_count": str(s["n_ow_pairs"]),
                "exact_position_balance": s["ow_pos"],
                "evidence_campaign": s["evidence_campaign"],
            })
            superseded_manifest.append({
                "workload": key[0], "strategy": key[1],
                "R_ws": round(R_ws, 4),
                "old_R_ow": round(old_R_ow, 4),
                "new_R_ow": round(R_ow, 4),
                "old_cat_ow": category(old_R_ow),
                "new_cat_ow": category(R_ow),
                "old_sign_agree": category(R_ws) == category(old_R_ow),
                "new_sign_agree": category(R_ws) == category(R_ow),
                "evidence_campaign": s["evidence_campaign"],
                "execution_git_sha": s["execution_git_sha"],
                "run_config_sha256": s["run_config_sha256"],
                "pair_count": s["n_ow_pairs"],
                "n_seeds": s["n_ow_seeds"],
                "position_balance": s["ow_pos"],
                "exact_position_balance": s["ow_pos"],
                "baseline_first_R_ow": round(s["baseline_first_R_ow"], 4),
                "target_first_R_ow": round(s["target_first_R_ow"], 4),
                "position_sensitive": s["position_sensitive"],
                "position_effect_direction": s["position_effect_direction"],
                "precedence": PRECEDENCE[key],
                "reason": REASON[key],
                "provenance_diagnostics": str(
                    (SIXTH_DIAG if s["evidence_campaign"] == SIXTH else SEVENTH_DIAG)
                    .relative_to(OW.parents[1])),
                "provenance_normalized_pairs": str(
                    (SIXTH_PAIRS if s["evidence_campaign"] == SIXTH else SEVENTH_PAIRS)
                    .relative_to(OW.parents[1])),
            })
        out_rows.append(row)

    if len(superseded_manifest) != 7:
        raise SystemExit(
            f"FAIL-CLOSED: expected 7 superseded cells, wrote {len(superseded_manifest)}")

    # ---- preserve historical freeze byte-identically ----
    HIST_FREEZE.write_bytes(hist_bytes)

    # ---- write the revised freeze ----
    fields = list(hist_rows[0].keys()) + META_FIELDS
    with open(REVISED, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields, lineterminator="\n")
        w.writeheader()
        for row in out_rows:
            w.writerow(row)
    revised_sha = hashlib.sha256(REVISED.read_bytes()).hexdigest()

    # ---- supersession manifest ----
    manifest = {
        "revision_id": REVISION_ID,
        "revision_date": REVISION_DATE,
        "policy": (
            "One-time pre-registered revision of the frozen OpenWhisk-vs-workstation "
            "effectiveness table. Supersedes exactly 7 of 55 first-query cells with their "
            "targeted, independently rebuilt, exactly position-balanced replication "
            "estimates. Historical freeze preserved byte-identically; nothing deleted; the "
            "revised freeze is the single paper-facing input. This is the FINAL freeze for "
            "paper writing -- no further OpenWhisk reruns, no automatic cell replacement."),
        "historical_source_path": str(HISTORICAL.relative_to(OW.parents[1])),
        "historical_source_sha256": hist_sha,
        "historical_freeze_path": str(HIST_FREEZE.relative_to(OW.parents[1])),
        "revised_freeze_path": str(REVISED.relative_to(OW.parents[1])),
        "revised_freeze_sha256": revised_sha,
        "total_cells": 55,
        "superseded_cell_count": 7,
        "unchanged_cell_count": 48,
        "coverage": "65/65",
        "coverage_note": "55 first-query cells + 10 libprefetch delivery-order cells = 65 matched.",
        "pooled": False,
        "pooled_note": (
            "Seven immutable OpenWhisk campaigns; NEVER pooled into one estimator. The "
            "revision changes which audited per-cell estimate is SELECTED for 7 cells; it "
            "does not pool campaigns and does not change coverage (65/65)."),
        "campaigns": [
            {"campaign": "primary", "run_config_sha256_prefix": "022fbeb0"},
            {"campaign": "secondary", "run_config_sha256_prefix": "441609e6"},
            {"campaign": "portability", "run_config_sha256_prefix": "64f44c3e"},
            {"campaign": "portability_ext", "run_config_sha256_prefix": "bf504a28"},
            {"campaign": "portability_full_closure", "run_config_sha256_prefix": "a5be8f15"},
            {"campaign": SIXTH, "run_config_sha256": SIXTH_RUN_CONFIG,
             "execution_git_sha": SIXTH_GIT_SHA},
            {"campaign": SEVENTH, "run_config_sha256": SEVENTH_RUN_CONFIG,
             "execution_git_sha": SEVENTH_GIT_SHA},
        ],
        "precedence_rule": "seventh > sixth > historical, applied per cell only where a "
                           "later campaign actually targeted that cell.",
        "position_sensitive_semantics": (
            "position_sensitive=true means the balanced aggregate is a descriptive "
            "balanced-batch estimate, NOT a clean position-independent causal effect: the "
            "baseline-first and target-first subsets carry opposite signs. The effect is a "
            "pair-position / short-lived execution-state / execution-storage-state "
            "dependence and is NOT attributed to page-cache carryover."),
        "superseded_cells": superseded_manifest,
    }
    with open(MANIFEST, "w") as f:
        json.dump(manifest, f, indent=2)
        f.write("\n")

    # ---- console summary ----
    print(f"historical freeze  : {HISTORICAL.name}  sha256={hist_sha}")
    print(f"historical snapshot: {HIST_FREEZE.name} (byte-identical)")
    print(f"revised freeze      : {REVISED.name}  sha256={revised_sha}")
    print(f"manifest            : {MANIFEST.name}")
    print(f"cells: 55 total, 7 superseded, 48 unchanged")
    print("\nsuperseded cells (old R_ow -> new R_ow, campaign, position_sensitive):")
    for s in superseded_manifest:
        print(f"  {s['workload']:6}/{s['strategy']:10} "
              f"{s['old_R_ow']:+.4f} -> {s['new_R_ow']:+.4f}  "
              f"{s['evidence_campaign']:32} pos_sensitive={s['position_sensitive']} "
              f"pairs={s['pair_count']} bal={s['position_balance']}")


if __name__ == "__main__":
    build()
